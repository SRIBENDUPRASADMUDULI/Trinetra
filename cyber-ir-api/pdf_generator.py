from fpdf import FPDF
import re


def _safe_text(text: str) -> str:
    """Replace non-Latin-1 characters that Helvetica cannot render."""
    # Replace common Unicode symbols with ASCII equivalents
    replacements = {
        "\u20b9": "Rs.",   # ₹
        "\u2014": "--",    # em dash
        "\u2013": "-",     # en dash
        "\u2018": "'",     # left single quote
        "\u2019": "'",     # right single quote
        "\u201c": '"',     # left double quote
        "\u201d": '"',     # right double quote
        "\u2026": "...",   # ellipsis
        "\u2022": "*",     # bullet
        "\u00a0": " ",     # non-breaking space
    }
    for char, repl in replacements.items():
        text = text.replace(char, repl)
    # Strip any remaining non-Latin-1 chars
    result = []
    for c in text:
        try:
            c.encode("latin-1")
            result.append(c)
        except UnicodeEncodeError:
            result.append("?")
    return "".join(result)


class FIRPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 8, "INDIA - CYBER CRIME", 0, 1, "C")
        self.set_font("Helvetica", "B", 16)
        self.cell(0, 10, "FIRST INFORMATION REPORT", 0, 1, "C")
        self.set_font("Helvetica", "", 9)
        self.cell(0, 5, "(Generated by AI for informational purposes)", 0, 1, "C")
        self.line(10, self.get_y() + 2, 200, self.get_y() + 2)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.cell(0, 10, f"Cyber-IR API | Page {self.page_no()}/{{nb}} | For informational purposes only", 0, 0, "C")

    def _reset_x(self):
        self.set_x(self.l_margin)

    def section_title(self, title):
        self._reset_x()
        self.set_font("Helvetica", "B", 11)
        self.set_fill_color(230, 230, 230)
        self.cell(0, 7, f"  {_safe_text(title)}", 0, 1, "L", fill=True)
        self.ln(2)

    def field(self, label, value):
        self._reset_x()
        self.set_font("Helvetica", "B", 9)
        self.cell(55, 5, f"{_safe_text(label)}:", 0, 0)
        self.set_font("Helvetica", "", 9)
        w = self.w - self.r_margin - self.get_x()
        self.multi_cell(w, 5, _safe_text(str(value) if value else "N/A"))
        self.ln(1)

    def body_text(self, text):
        self._reset_x()
        self.set_font("Helvetica", "", 9)
        self.multi_cell(0, 5, _safe_text(str(text) if text else "N/A"))
        self.ln(2)

    def bullet_list(self, items):
        self.set_font("Helvetica", "", 9)
        for item in items or []:
            self._reset_x()
            self.multi_cell(0, 5, _safe_text(f"  - {item}"))
        self.ln(2)

    def label(self, text):
        self._reset_x()
        self.set_font("Helvetica", "B", 9)
        self.cell(0, 5, _safe_text(text), 0, 1)


def generate_fir_pdf(data: dict) -> bytes:
    pdf = FIRPDF()
    pdf.alias_nb_pages()
    pdf.add_page()

    # FIR Number + Date
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(95, 7, f"FIR No: {_safe_text(data.get('fir_number', 'CYB-2026-PENDING'))}", 0, 0)
    pdf.cell(95, 7, f"Date: {_safe_text(data.get('date_of_report', data.get('incident_date', 'N/A')))}", 0, 1, "R")
    pdf.ln(3)

    # Complainant Details
    c = data.get("complainant", {})
    pdf.section_title("1. COMPLAINANT DETAILS")
    pdf.field("Name", c.get("name"))
    pdf.field("Date of Birth", c.get("dob"))
    pdf.field("Father/Mother/Spouse", c.get("parent_name"))
    pdf.field("Email", c.get("email"))
    pdf.field("Address", c.get("address"))
    pdf.field("ID Proof", c.get("id_proof"))

    # Incident Details
    inc = data.get("incident", {})
    pdf.section_title("2. INCIDENT DETAILS")
    pdf.field("Category", inc.get("category"))
    pdf.field("Sub-Category", inc.get("subcategory"))
    pdf.field("Date & Time", inc.get("date_time"))
    pdf.field("Location", inc.get("location"))
    pdf.label("Description:")
    pdf.body_text(inc.get("description", ""))

    # Accused Details
    acc = data.get("accused", {})
    pdf.section_title("3. ACCUSED DETAILS")
    pdf.field("Description", acc.get("description"))
    pdf.field("Contact Details", acc.get("contact_details"))
    pdf.field("Bank Details", acc.get("bank_details"))

    # Technical Analysis
    tech = data.get("technical_analysis", {})
    pdf.section_title("4. TECHNICAL ANALYSIS")
    pdf.field("Attack Vector", tech.get("attack_vector"))
    pdf.label("Indicators of Compromise:")
    pdf.bullet_list(tech.get("indicators_of_compromise", []))
    pdf.label("Evidence Collected:")
    pdf.bullet_list(tech.get("evidence_collected", []))

    # Legal Provisions
    legal = data.get("legal_provisions", {})
    pdf.section_title("5. APPLICABLE LEGAL PROVISIONS")

    pdf.label("Bharatiya Nyaya Sanhita (BNS) 2023:")
    for s in legal.get("bns_sections", []):
        pdf._reset_x()
        pdf.set_font("Helvetica", "", 9)
        pdf.multi_cell(0, 5, _safe_text(f"  - {s.get('section', 'N/A')}: {s.get('offence', 'N/A')}"))
    pdf.ln(1)

    pdf.label("Information Technology Act, 2000:")
    for s in legal.get("it_act_sections", []):
        pdf._reset_x()
        pdf.set_font("Helvetica", "", 9)
        pdf.multi_cell(0, 5, _safe_text(f"  - {s.get('section', 'N/A')}: {s.get('offence', 'N/A')}"))
    pdf.ln(1)

    if legal.get("other_applicable_laws"):
        pdf.label("Other Applicable Laws:")
        pdf.bullet_list(legal.get("other_applicable_laws", []))

    # Financial Loss
    fin = data.get("financial_loss", {})
    if fin and fin.get("amount") and fin["amount"] != "N/A":
        pdf.section_title("6. FINANCIAL LOSS DETAILS")
        pdf.field("Amount", fin.get("amount"))
        pdf.field("Transaction Details", fin.get("transaction_details"))

    # Prayer / Relief
    pdf.section_title("7. PRAYER / RELIEF SOUGHT")
    pdf.bullet_list(data.get("prayer_relief", []))

    # Verification
    v = data.get("verification", {})
    pdf.section_title("8. VERIFICATION")
    pdf.field("Place", v.get("place"))
    pdf.field("Date", v.get("date"))
    pdf.ln(10)
    pdf._reset_x()
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(0, 5, "_" * 40, 0, 1)
    pdf.cell(0, 5, "Signature of Complainant", 0, 1, "C")

    return bytes(pdf.output())
